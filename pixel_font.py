def get_glyph(char, font_type="normal"):
    """Returns (pixel_coords, width) for character, with fallbacks."""
    table = FONT_NORMAL if font_type == "normal" else (
        FONT_CLOCK if font_type == "clock" else FONT_MINI)

    if char in table:
        return table[char]
    if char in SUBSTITUTIONS and SUBSTITUTIONS[char] in table:
        return table[SUBSTITUTIONS[char]]

    # Uppercase fallback if lowercase missing in mini font
    upper = char.upper()
    if upper in table:
        return table[upper]

    # Default fallback: space for whitespace, or question mark
    if char.isspace():
        return table.get(" ", ([], 2))
    return table.get("?", ([], 3))


def measure_text(text, font_type="normal", spacing=1):
    """Calculates total pixel width of text."""
    if not text:
        return 0
    total = 0
    for i, ch in enumerate(text):
        _, w = get_glyph(ch, font_type)
        total += w + (spacing if i > 0 else 0)
    return total


def draw_text(image, xy, text, fill, font_type="normal", spacing=1):
    """Draws crisp pixel text directly onto a PIL Image."""
    draw = ImageDraw.Draw(image)
    x, y = xy
    cursor_x = x
    for i, ch in enumerate(text):
        if i > 0:
            cursor_x += spacing
        coords, w = get_glyph(ch, font_type)
        for px, py in coords:
            draw.point((cursor_x + px, y + py), fill=fill)
        cursor_x += w
    return cursor_x - x


def create_text_strip(parts, height=9, font_type="normal", spacing=1, y_offset=1, shaded=True):
    """Creates an RGB text strip from a list of (text, colour) tuples.

    Returns (image, width).
    """
    total_w = 0
    for text, _ in parts:
        total_w += measure_text(text, font_type=font_type, spacing=spacing)
    total_w = max(1, total_w)

    strip = Image.new("RGB", (total_w, height), "black")
    cursor_x = 0
    for text, colour in parts:
        w = draw_text(strip, (cursor_x, y_offset), text, fill=colour, font_type=font_type, spacing=spacing)
        cursor_x += w

    if shaded:
        # Subtle vertical depth: keep upper strokes 100% bright, shade lower rows slightly
        shade_y = y_offset + (3 if font_type == "mini" else 4)
        for py in range(shade_y, height):
            factor = 0.82 if py == shade_y else 0.68
            for px in range(total_w):
                r, g, b = strip.getpixel((px, py))
                if r or g or b:
                    strip.putpixel((px, py), (int(r * factor), int(g * factor), int(b * factor)))

    return strip, total_w
