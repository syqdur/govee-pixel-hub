def _compile_glyph(raw_rows):
    """Parses row patterns into list of (x, y) relative pixel coords and width."""
    coords = []
    width = 0
    for y, row in enumerate(raw_rows):
        width = max(width, len(row))
        for x, char in enumerate(row):
            if char in ("#", "1", "X"):
                coords.append((x, y))
    return coords, max(width, 1)


